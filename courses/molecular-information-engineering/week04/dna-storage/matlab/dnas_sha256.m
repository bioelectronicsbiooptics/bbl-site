function digest = dnas_sha256(bytes)
% 파일 식별값: JVM · 툴박스 없이 SHA-256을 계산한다.
persistent K initial
if isempty(K)
    hex = ['428a2f98'; '71374491'; 'b5c0fbcf'; 'e9b5dba5'; ...
        '3956c25b'; '59f111f1'; '923f82a4'; 'ab1c5ed5'; ...
        'd807aa98'; '12835b01'; '243185be'; '550c7dc3'; ...
        '72be5d74'; '80deb1fe'; '9bdc06a7'; 'c19bf174'; ...
        'e49b69c1'; 'efbe4786'; '0fc19dc6'; '240ca1cc'; ...
        '2de92c6f'; '4a7484aa'; '5cb0a9dc'; '76f988da'; ...
        '983e5152'; 'a831c66d'; 'b00327c8'; 'bf597fc7'; ...
        'c6e00bf3'; 'd5a79147'; '06ca6351'; '14292967'; ...
        '27b70a85'; '2e1b2138'; '4d2c6dfc'; '53380d13'; ...
        '650a7354'; '766a0abb'; '81c2c92e'; '92722c85'; ...
        'a2bfe8a1'; 'a81a664b'; 'c24b8b70'; 'c76c51a3'; ...
        'd192e819'; 'd6990624'; 'f40e3585'; '106aa070'; ...
        '19a4c116'; '1e376c08'; '2748774c'; '34b0bcb5'; ...
        '391c0cb3'; '4ed8aa4a'; '5b9cca4f'; '682e6ff3'; ...
        '748f82ee'; '78a5636f'; '84c87814'; '8cc70208'; ...
        '90befffa'; 'a4506ceb'; 'bef9a3f7'; 'c67178f2'];
    K = uint32(hex2dec(hex))';
    initial = uint32(hex2dec(['6a09e667'; 'bb67ae85'; ...
        '3c6ef372'; 'a54ff53a'; '510e527f'; '9b05688c'; ...
        '1f83d9ab'; '5be0cd19']))';
end
bytes = reshape(uint8(bytes), 1, []);
bitLength = numel(bytes)*8;
bytes(end + 1) = 128;
bytes(end + 1:end + mod(56 - numel(bytes), 64)) = 0;
bytes = [bytes uint8(mod(floor(bitLength ./ 256.^(7:-1:0)), 256))];
H = initial;
for start = 1:64:numel(bytes)
    block = reshape(double(bytes(start:start + 63)), 4, 16);
    W = zeros(1, 64, 'uint32');
    W(1:16) = uint32([2^24 2^16 2^8 1] * block);
    for j = 17:64
        v = W(j - 15); u = W(j - 2);
        s0 = bitxor(bitxor(rotr(v, 7), rotr(v, 18)), bitshift(v, -3));
        s1 = bitxor(bitxor(rotr(u, 17), rotr(u, 19)), bitshift(u, -10));
        W(j) = add([W(j - 16) s0 W(j - 7) s1]);
    end
    v = H;
    for j = 1:64
        S1 = bitxor(bitxor(rotr(v(5), 6), rotr(v(5), 11)), ...
            rotr(v(5), 25));
        choose = bitxor(bitand(v(5), v(6)), ...
            bitand(bitcmp(v(5)), v(7)));
        t1 = add([v(8) S1 choose K(j) W(j)]);
        S0 = bitxor(bitxor(rotr(v(1), 2), rotr(v(1), 13)), ...
            rotr(v(1), 22));
        majority = bitxor(bitxor(bitand(v(1), v(2)), ...
            bitand(v(1), v(3))), bitand(v(2), v(3)));
        t2 = add([S0 majority]);
        v = [add([t1 t2]) v(1:3) add([v(4) t1]) v(5:7)];
    end
    H = uint32(mod(double(H) + double(v), 2^32));
end
digest = lower(reshape(dec2hex(H, 8)', 1, []));
end

function y = rotr(x, count)
% SHA-256 보조 함수: uint32를 오른쪽 순환 이동한다.
y = bitor(bitshift(x, -count), bitshift(x, 32 - count));
end

function y = add(values)
% SHA-256 보조 함수: 포화 대신 modulo 2^32 덧셈.
y = uint32(mod(sum(double(values)), 2^32));
end
